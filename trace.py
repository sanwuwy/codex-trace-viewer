#!/usr/bin/env python3
"""Run the trace controller directly, without a model turn."""
import argparse
import base64
import importlib.util
import json
import os
from pathlib import Path
import re
import shlex
import sys
from urllib.parse import urlencode
import webbrowser

PROJECT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location(
    "trace_controller", PROJECT / ".agents/skills/codex-trace/scripts/viewer.py")
viewer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(viewer)


def codex_url(thread, url):
    if not re.fullmatch(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", thread):
        raise viewer.ControllerError("打开 Codex 面板需要 UUID 会话 ID；可去掉 --open-codex 使用系统浏览器。")
    # Verified against the installed desktop URL handler; not a public stable API.
    return "codex://threads/" + thread + "?" + urlencode(
        {"browserUrl": url, "browserTabId": "codex-trace-" + thread})


def open_page(result, native):
    target = codex_url(result["thread_id"], result["url"]) if native else result["url"]
    error_message = "页面打开请求未被系统接受"
    try:
        requested = webbrowser.open(target)
    except (webbrowser.Error, OSError) as error:
        requested = False
        error_message = str(error)
    if native and not requested:
        result["warning"] = "Codex 链接未能派发，已尝试系统浏览器：" + error_message
        return open_page(result, False)
    result.update(browser_requested=bool(requested), browser_target="codex" if native else "browser")
    if not requested:
        result["error"] = "服务已就绪，但页面未能打开；请访问返回的 URL。" + error_message
    return bool(requested)


def write_actions(path, text):
    if path.is_symlink():
        raise viewer.ControllerError("Actions 文件是符号链接，未覆盖：" + str(path))
    try:
        with path.open("x", encoding="utf-8", newline="") as stream:
            stream.write(text)
    except FileExistsError:
        if (path.is_symlink() or path.stat().st_size != len(text.encode("utf-8")) or
                path.read_text(encoding="utf-8") != text):
            raise viewer.ControllerError("已有不同的 Actions 配置，未覆盖：" + str(path))


def generate_shortcuts(thread, open_codex=False, install_actions=False):
    thread = viewer.thread_id(thread)
    if open_codex:
        codex_url(thread, "http://127.0.0.1")
    root = viewer.state_dir().parent
    directory = root / "trace-viewer" / "shortcuts" / thread
    actions_path = PROJECT / ".codex" / "environments" / ("codex-trace-" + thread + ".toml")
    windows = sys.platform == "win32"
    suffix = ".cmd" if windows else ".command" if sys.platform == "darwin" else ".sh"
    files, actions, scripts = [], [], []
    for operation, label in (("start", "启动轨迹"), ("stop", "停止轨迹"),
                             ("start-all", "启动全部轨迹"), ("stop-all", "停止全部轨迹")):
        arguments = [sys.executable, str(PROJECT / "trace.py"), operation]
        if not operation.endswith("-all"):
            arguments += ["--thread", thread]
        if operation == "start" and open_codex:
            arguments += ["--open-codex"]
        path = directory / (operation + suffix)
        if windows:
            # Batch expansion of '%' also applies inside quotes; disable delayed '!'.
            quote = lambda value: '"' + value.replace('%', '%%') + '"'
            command = " ".join(quote(value) for value in arguments)
            script = ('@echo off\r\nsetlocal DisableDelayedExpansion\r\nchcp 65001 >nul\r\nset "CODEX_HOME=' +
                      str(root).replace('%', '%%') + '"\r\n' + command +
                      '\r\nset "trace_exit=%ERRORLEVEL%"\r\nif not "%trace_exit%"=="0" pause\r\nexit /b %trace_exit%\r\n')
            # An ASCII command works in CMD and PowerShell; encoding preserves paths.
            powershell = "& '" + str(path).replace("'", "''") + "'"
            encoded = base64.b64encode(powershell.encode("utf-16-le")).decode("ascii")
            action = "powershell.exe -NoLogo -NoProfile -NonInteractive -EncodedCommand " + encoded
        else:
            command = "CODEX_HOME=" + shlex.quote(str(root)) + " " + " ".join(shlex.quote(value) for value in arguments)
            script = ("#!/bin/sh\n" + command + '\ntrace_exit=$?\n'
                      'if [ "$trace_exit" -ne 0 ]; then\n'
                      '  printf "按回车关闭…"\n  read -r trace_reply\nfi\nexit "$trace_exit"\n')
            action = command
        files.append(str(path))
        scripts.append((path, script))
        actions.append((label + (" · " + thread[:8] if not operation.endswith("-all") else ""),
                        "run" if operation.startswith("start") else "tool", action))
    text = ('# Generated by codex-trace; bound to this explicit conversation.\nversion = 1\nname = ' +
            json.dumps("会话轨迹 · " + thread, ensure_ascii=False) + '\n\n[setup]\nscript = ""\n')
    for name, icon, command in actions:
        text += ("\n[[actions]]\nname = " + json.dumps(name, ensure_ascii=False) +
                 "\nicon = " + json.dumps(icon) + "\ncommand = " + json.dumps(command, ensure_ascii=False) +
                 "\nplatform = " + json.dumps(sys.platform) + "\n")
    if install_actions and actions_path.exists() and actions_path.read_text(encoding="utf-8") != text:
        raise viewer.ControllerError("已有不同的 Actions 配置，未覆盖：" + str(actions_path))
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    for path, script in scripts:
        if path.is_symlink():
            raise viewer.ControllerError("快捷文件是符号链接，未覆盖：" + str(path))
        with path.open("w", encoding="utf-8", newline="") as stream:
            stream.write(script)
        if not windows:
            path.chmod(0o700)
    template = directory / "actions.toml"
    if template.is_symlink() or actions_path.is_symlink():
        raise viewer.ControllerError("Actions 文件是符号链接，未覆盖。")
    write_actions(template, text)
    if install_actions:
        actions_path.parent.mkdir(parents=True, exist_ok=True)
        write_actions(actions_path, text)
    return {"thread_id": thread, "directory": str(directory), "files": files,
            "actions_file": str(actions_path if install_actions else template),
            "actions_installed": install_actions}


def main(argv=None):
    parser = argparse.ArgumentParser(description="直接启动、停止轨迹或生成会话专属快捷入口")
    parser.add_argument("command", choices=("start", "stop", "status", "start-all", "stop-all", "shortcuts"))
    parser.add_argument("--thread", help="明确绑定的会话 ID；省略时使用可信 CODEX_THREAD_ID")
    parser.add_argument("--no-open", action="store_true", help="只管理服务并返回 URL，不打开页面")
    parser.add_argument("--open-codex", action="store_true", help="独立轨迹通过本机 Codex 链接打开右侧面板")
    parser.add_argument("--install-actions", action="store_true", help="生成快捷入口时安装项目内的专属 Actions 环境")
    args = parser.parse_args(argv)
    if args.command.endswith("-all") and args.thread is not None:
        parser.error("全部操作禁止使用 --thread")
    if args.open_codex and args.command not in ("start", "shortcuts"):
        parser.error("--open-codex 只用于独立轨迹 start 或 shortcuts")
    if args.no_open and args.command not in ("start", "start-all"):
        parser.error("--no-open 只用于 start 或 start-all")
    if args.no_open and args.open_codex:
        parser.error("--no-open 与 --open-codex 不能同时使用")
    if args.install_actions and args.command != "shortcuts":
        parser.error("--install-actions 只用于 shortcuts")
    try:
        thread = None if args.command.endswith("-all") else viewer.thread_id(args.thread)
        if args.open_codex:
            codex_url(thread, "http://127.0.0.1")
        if args.command == "shortcuts":
            result = generate_shortcuts(thread, args.open_codex, args.install_actions)
        elif args.command == "stop-all":
            result = viewer.stop_all()
        else:
            result = viewer.control("start" if args.command == "start-all" else args.command, thread)
        failed = bool(result.get("errors"))
        if args.command in ("start", "start-all") and not args.no_open:
            failed = not open_page(result, args.open_codex)
    except (viewer.ControllerError, OSError, ValueError) as error:
        message = str(error)
        if args.thread is None and not os.environ.get("CODEX_THREAD_ID") and not args.command.endswith("-all"):
            message += " Actions 不自动提供当前聊天 ID；请使用 --thread，或用 $codex-trace 生成快捷入口。"
        print(json.dumps({"error": message}, ensure_ascii=False), file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=False), file=sys.stderr if failed else sys.stdout)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
